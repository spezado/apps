// Generates the Dart client of spezado's API from its OpenAPI description: a class per schema, with `fromJson` and
// `toJson`, and a method per operation. Nothing of the API is written by hand; the transport underneath is.
//
//   dart run tool/generate.dart [api/openapi.json] [lib/api/api.g.dart]
//
// spezado's description follows one style (utoipa, OpenAPI 3.1): objects with properties; `type: [T, "null"]` and
// `oneOf: [{$ref}, {type: null}]` for what may be null; JSON in and out, files as `application/octet-stream`.
// Anything else stops the generator, so that a new construct is handled on purpose.

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final input = args.isNotEmpty ? args[0] : 'api/openapi.json';
  final output = args.length > 1 ? args[1] : 'lib/api/api.g.dart';
  final spec = jsonDecode(File(input).readAsStringSync()) as Map<String, Object?>;
  File(output).writeAsStringSync(Generator(spec).run());
  final format = Process.runSync('dart', ['format', '--page-width', '120', output]);
  if (format.exitCode != 0) {
    stderr.write(format.stderr);
    exit(format.exitCode);
  }
}

/// A Dart type and how it is read from JSON and written to it.
class DartType {
  const DartType(this.name, this.read, this.write, {this.nullable = false});

  final String name;

  /// Reads the value from an expression of type `Object?`.
  final String Function(String json) read;

  /// Writes the value of a non-null expression.
  final String Function(String value) write;

  final bool nullable;

  String get declared => nullable ? '$name?' : name;

  DartType get orNull =>
      nullable ? this : DartType(name, (json) => '$json == null ? null : ${read(json)}', write, nullable: true);
}

class Generator {
  Generator(this.spec);

  final Map<String, Object?> spec;
  final out = StringBuffer();

  Map<String, Object?> get schemas => (spec['components'] as Map)['schemas'] as Map<String, Object?>;

  String run() {
    final info = spec['info'] as Map;
    out
      // REUSE-IgnoreStart
      ..writeln('// SPDX-License-Identifier: MIT')
      // REUSE-IgnoreEnd
      ..writeln('// GENERATED by tool/generate.dart from api/openapi.json – do not edit.')
      ..writeln('// ${info['title']} ${info['version']}: ${info['description']}')
      ..writeln()
      ..writeln('// ignore_for_file: unnecessary_cast')
      ..writeln()
      ..writeln("import 'dart:typed_data';")
      ..writeln()
      ..writeln("import 'transport.dart';")
      ..writeln()
      ..writeln('/// The version of the API this client was generated from.')
      ..writeln("const apiVersion = '${info['version']}';")
      ..writeln();
    for (final entry in schemas.entries) {
      model(entry.key, entry.value as Map<String, Object?>);
    }
    client();
    return out.toString();
  }

  Never unsupported(String where, Object? what) => throw UnsupportedError('$where: ${jsonEncode(what)}');

  /// The Dart type of a schema.
  DartType type(Map<String, Object?> schema, String where) {
    if (schema[r'$ref'] case final String ref) {
      final name = ref.split('/').last;
      return DartType(name, (json) => '$name.fromJson($json as Map<String, Object?>)', (value) => '$value.toJson()');
    }
    if (schema['oneOf'] case final List<Object?> options) {
      final rest = options.cast<Map<String, Object?>>().where((option) => option['type'] != 'null').toList();
      if (rest.length != 1 || options.length != 2) unsupported(where, schema);
      return type(rest.single, where).orNull;
    }
    final kind = schema['type'];
    if (kind is List) {
      final rest = kind.where((k) => k != 'null').toList();
      if (rest.length != 1 || kind.length != 2) unsupported(where, schema);
      return type({...schema, 'type': rest.single}, where).orNull;
    }
    switch (kind) {
      case 'string':
        return DartType('String', (json) => '$json as String', (value) => value);
      case 'integer':
        return DartType('int', (json) => '($json as num).toInt()', (value) => value);
      case 'number':
        return DartType('double', (json) => '($json as num).toDouble()', (value) => value);
      case 'boolean':
        return DartType('bool', (json) => '$json as bool', (value) => value);
      case 'array':
        final item = type(schema['items'] as Map<String, Object?>, '$where[]');
        if (item.nullable) unsupported(where, schema);
        return DartType(
          'List<${item.name}>',
          (json) => '($json as List<Object?>).map((e) => ${item.read('e')}).toList()',
          // Strings and numbers are written as they are; objects one by one.
          (value) => item.write('e') == 'e' ? value : '$value.map((e) => ${item.write('e')}).toList()',
        );
    }
    unsupported(where, schema);
  }

  void docs(Object? text, {String indent = ''}) {
    if (text is! String || text.trim().isEmpty) return;
    for (final line in text.trim().split('\n')) {
      out.writeln('$indent/// ${line.trim()}'.trimRight());
    }
  }

  void model(String name, Map<String, Object?> schema) {
    if (schema['type'] != 'object' || schema['properties'] is! Map) unsupported(name, schema);
    final required = ((schema['required'] as List?) ?? const []).cast<String>().toSet();
    final properties = (schema['properties'] as Map).cast<String, Map<String, Object?>>();
    final fields = [
      for (final MapEntry(key: json, value: property) in properties.entries)
        (
          json: json,
          dart: field(json),
          type: required.contains(json) ? type(property, '$name.$json') : type(property, '$name.$json').orNull,
          docs: property['description'] ?? _oneOfDescription(property),
        ),
    ];
    docs(schema['description']);
    out.writeln('class $name {');
    out.writeln('  const $name({');
    for (final f in fields) {
      out.writeln('    ${f.type.nullable ? '' : 'required '}this.${f.dart},');
    }
    out.writeln('  });');
    out.writeln();
    out.writeln('  factory $name.fromJson(Map<String, Object?> json) => $name(');
    for (final f in fields) {
      out.writeln("    ${f.dart}: ${f.type.read("json['${f.json}']")},");
    }
    out.writeln('  );');
    for (final f in fields) {
      out.writeln();
      docs(f.docs, indent: '  ');
      out.writeln('  final ${f.type.declared} ${f.dart};');
    }
    out.writeln();
    out.writeln('  Map<String, Object?> toJson() => {');
    for (final f in fields) {
      // What is null is left out: spezado reads a missing field as none.
      final plain = f.type.write(f.dart) == f.dart;
      final value = !f.type.nullable ? f.type.write(f.dart) : (plain ? '?${f.dart}' : '?${f.type.write('${f.dart}?')}');
      out.writeln("    '${f.json}': $value,");
    }
    out.writeln('  };');
    out.writeln('}');
    out.writeln();
  }

  Object? _oneOfDescription(Map<String, Object?> property) =>
      (property['oneOf'] as List?)?.cast<Map<String, Object?>>().map((o) => o['description']).nonNulls.firstOrNull;

  void client() {
    out.writeln('/// The operations of the API, each a call through the transport.');
    out.writeln('class SpezadoApi {');
    out.writeln('  const SpezadoApi(this.transport);');
    out.writeln();
    out.writeln('  final Transport transport;');
    final paths = (spec['paths'] as Map).cast<String, Map<String, Object?>>();
    for (final MapEntry(key: path, value: methods) in paths.entries) {
      for (final MapEntry(key: method, value: operation) in methods.entries) {
        this.operation(path, method, operation as Map<String, Object?>);
      }
    }
    out.writeln('}');
  }

  void operation(String path, String method, Map<String, Object?> operation) {
    final id = operation['operationId'] as String;
    final responses = (operation['responses'] as Map).cast<String, Map<String, Object?>>();
    final ok = (responses['200']?['content'] as Map?)?.cast<String, Map<String, Object?>>() ?? const {};
    // Server-Sent Events are a stream, not an answer: the transport follows them.
    if (ok.isEmpty && method == 'get') return;

    final parameters = ((operation['parameters'] as List?) ?? const []).cast<Map<String, Object?>>();
    final arguments = <String>[];
    final pathArguments = <String, String>{};
    final queryArguments = <String, String>{};
    for (final parameter in parameters) {
      final json = parameter['name'] as String;
      final dart = field(json);
      final required = parameter['required'] == true;
      var kind = type(parameter['schema'] as Map<String, Object?>, '$id.$json');
      if (!required) kind = kind.orNull;
      arguments.add('${kind.nullable ? '' : 'required '}${kind.declared} $dart');
      switch (parameter['in']) {
        case 'path':
          pathArguments[json] = dart;
        case 'query':
          queryArguments[json] = dart;
        default:
          unsupported('$id.$json', parameter);
      }
    }

    final request =
        ((operation['requestBody'] as Map?)?['content'] as Map?)?.cast<String, Map<String, Object?>>() ?? const {};
    String? body;
    String? bytes;
    if (request.containsKey('application/json')) {
      final kind = type(request['application/json']!['schema'] as Map<String, Object?>, '$id body');
      arguments.add('required ${kind.declared} body');
      body = kind.write('body');
    } else if (request.containsKey('application/octet-stream')) {
      arguments.add('required Uint8List file');
      bytes = 'file';
    } else if (request.isNotEmpty) {
      unsupported('$id body', request);
    }

    late final String result;
    late final String Function(String) read;
    var answer = 'json';
    if (ok.containsKey('application/json')) {
      final kind = type(ok['application/json']!['schema'] as Map<String, Object?>, '$id answer');
      result = kind.declared;
      read = kind.read;
    } else if (ok.keys.any((media) => media != 'application/json')) {
      result = 'Uint8List';
      read = (json) => json;
      answer = 'bytes';
    } else {
      result = 'void';
      read = (json) => json;
      answer = 'none';
    }

    final dartPath = path.replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) {
      final dart = pathArguments[m[1]] ?? unsupported('$id path', path);
      return '\${Uri.encodeComponent($dart)}';
    });
    final query = queryArguments.isEmpty
        ? ''
        : ', query: {${queryArguments.entries.map((e) => "'${e.key}': ${e.value}").join(', ')}}';
    final payload = [if (body != null) ', json: $body', if (bytes != null) ', bytes: $bytes'].join();

    out.writeln();
    docs(operation['summary']);
    final signature = arguments.isEmpty ? '' : '{${arguments.join(', ')}}';
    final call = "transport.$answer('${method.toUpperCase()}', '$dartPath'$query$payload)";
    final name = field(id);
    if (answer == 'none') {
      out.writeln('  Future<void> $name($signature) => $call;');
    } else if (answer == 'bytes') {
      out.writeln('  Future<Uint8List> $name($signature) => $call;');
    } else {
      out.writeln('  Future<$result> $name($signature) async => ${read('await $call')};');
    }
  }

  static const reserved = {'in', 'is', 'new', 'class', 'default', 'switch', 'case', 'var', 'const', 'final', 'enum'};

  /// A name of the API in Dart: `vat_scheme` → `vatScheme`.
  String field(String json) {
    final parts = json.split(RegExp(r'[_\-]'));
    final name = parts.first + parts.skip(1).map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1)).join();
    if (reserved.contains(name)) unsupported('a reserved word', name);
    return name;
  }
}
