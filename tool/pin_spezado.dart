// Pins the spezado release the desktop app installs: its version and, per platform, the archive and its SHA-256 as
// the release publishes them. The app checks every download against these, not against what the server says.
//
//   dart run tool/pin_spezado.dart 0.3.0

import 'dart:io';

/// spezado's release targets, by the platform the app runs on.
const targets = {
  'macos-arm64': ('aarch64-apple-darwin', 'tar.gz'),
  'windows-x64': ('x86_64-pc-windows-msvc', 'zip'),
  'linux-x64': ('x86_64-unknown-linux-gnu', 'tar.gz'),
  'linux-arm64': ('aarch64-unknown-linux-gnu', 'tar.gz'),
};

Future<void> main(List<String> args) async {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/pin_spezado.dart VERSION');
    exit(64);
  }
  final version = args.single;
  final client = HttpClient();
  final out = StringBuffer()
    // REUSE-IgnoreStart
    ..writeln('// SPDX-License-Identifier: MIT')
    // REUSE-IgnoreEnd
    ..writeln('// GENERATED by tool/pin_spezado.dart – do not edit.')
    ..writeln()
    ..writeln('/// The spezado release the app installs.')
    ..writeln("const spezadoVersion = '$version';")
    ..writeln()
    ..writeln('/// Per platform: the archive of the release and its SHA-256.')
    ..writeln('const spezadoArchives = <String, ({String file, String sha256})>{');
  for (final MapEntry(key: platform, value: (target, extension)) in targets.entries) {
    final file = 'spezado-$version-$target.$extension';
    final url = Uri.parse('https://github.com/spezado/spezado/releases/download/v$version/$file.sha256');
    final response = await (await client.getUrl(url)).close();
    final text = await response.transform(const SystemEncoding().decoder).join();
    if (response.statusCode != 200) {
      stderr.writeln('$url: ${response.statusCode}');
      exit(1);
    }
    final sha256 = text.trim().split(RegExp(r'\s+')).first;
    if (!RegExp(r'^[0-9a-f]{64}$').hasMatch(sha256)) {
      stderr.writeln('$url: no SHA-256');
      exit(1);
    }
    out.writeln("  '$platform': (file: '$file', sha256: '$sha256'),");
  }
  out.writeln('};');
  client.close();
  File('lib/install/release.g.dart').writeAsStringSync(out.toString());
}
